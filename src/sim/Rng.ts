/**
 * Seeded random numbers (mulberry32). Same seed → same battle, which makes balance testing
 * repeatable. Use this inside the simulation instead of Math.random().
 */
export class Rng {
  private s: number;

  constructor(seed = 0x0bad5eed) {
    this.s = seed >>> 0;
  }

  next(): number {
    let t = (this.s = (this.s + 0x6d2b79f5) >>> 0);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  range(min: number, max: number): number {
    return min + (max - min) * this.next();
  }

  chance(p: number): boolean {
    return this.next() < p;
  }
}
